import assert from "node:assert/strict";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { pathToFileURL } from "node:url";
import { main } from "../.agents/skills/review/round.mjs";
import { roundConnection } from "./fixtures/postern-review-round.mjs";
import { installedValidator } from "./helpers/installed-validator.mjs";

const head = "a".repeat(40);
const earlier = "b".repeat(40);
const reviewBody = (sha, findings = "None") => `> _This was generated by AI._

Head: ${sha}
Standards: Passed; CONTRIBUTING.md and the installed rules checked.
Spec: Passed; every acceptance criterion of #5 holds, and the brief matches the issue.
Fixed: Nothing
Findings: ${findings}`;
const handBack = (sha) =>
  reviewBody(sha, "").concat(
    "\n- `src/ledger.mjs:12` the pending total ignores refunds the brief requires.",
  );
const restReview = (body, extra = {}) => ({
  id: 1,
  user: { login: "reviewer", type: "User" },
  state: "COMMENTED",
  body,
  commit_id: head,
  submitted_at: "2026-11-06T11:00:00Z",
  ...extra,
});

/** @returns {any} The fixture's mutable pull request state. */
function pullState(pull = {}, extra = {}) {
  return {
    pull: { number: 12, head, draft: true, closes: [5], ...pull },
    issues: { 5: ["state:ready", "type:enhancement"] },
    ...extra,
  };
}

async function run(t, argv, state, entry = main) {
  let stdout = "";
  let stderr = "";
  t.mock.method(process.stdout, "write", (text) => {
    stdout += text;
    return true;
  });
  t.mock.method(process.stderr, "write", (text) => {
    stderr += text;
    return true;
  });
  const status = await entry(argv, roundConnection(state));
  t.mock.restoreAll();
  return { status, stdout, stderr };
}

function file(t, body) {
  const directory = mkdtempSync(join(tmpdir(), "review-round-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const path = join(directory, "review.md");
  writeFileSync(path, body);
  return path;
}

const facts = (stdout) =>
  Object.fromEntries(
    stdout
      .trim()
      .split("\n")
      .map((line) => [
        line.slice(0, line.indexOf(" ")),
        line.slice(line.indexOf(" ") + 1),
      ]),
  );

test("a fresh draft is round 1, unreviewed, with its closing issue and no gate", async (t) => {
  const result = await run(t, ["12"], pullState());
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(facts(result.stdout), {
    head,
    round: "1",
    reviewed: "no",
    held: "no",
    draft: "yes",
    issues: "#5",
    gates: "none",
  });
});

