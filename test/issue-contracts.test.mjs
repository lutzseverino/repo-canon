function requested(result, method, url) {
  return result.requests.some((candidate) => candidate.method === method && candidate.url === url);
}

function permissionLookups(result) {
  return result.requests
    .map(({ url }) => url.match(/^\/repos\/example\/repository\/collaborators\/([^/]+)\/permission$/)?.[1])
    .filter(Boolean)
    .map(decodeURIComponent)
    .sort();
}

function writes(result) {
  return result.requests
    .filter(({ method, url }) => method !== "GET" && url !== "/graphql")
    .map(({ method, url, body }) => [method, url, body ? JSON.parse(body) : null]);
}

