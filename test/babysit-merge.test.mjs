/** @param {string | URL} [target] */
function run(
  t,
  state,
  args = ["12", head],
  target = new URL("../.agents/skills/babysit/merge.mjs", import.meta.url),
) {
  const targetURL = typeof target === "string" ? pathToFileURL(target) : target;
  const bundleURL = new URL("../../../vendor/postern/postern.mjs", targetURL);
  const directory = mkdtempSync(join(tmpdir(), "babysit-merge-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const statePath = join(directory, "state.json");
  if (state.localReviewConfiguration?.factory) {
    mkdirSync(join(directory, ".scriptorium"));
    writeFileSync(
      join(directory, ".scriptorium/config.json"),
      JSON.stringify(state.localReviewConfiguration.factory),
    );
  }
  if (state.localReviewConfiguration) {
    mkdirSync(join(directory, ".github"));
    for (const [key, value] of Object.entries(state.localReviewConfiguration)) {
      if (key === "factory") continue;
      writeFileSync(
        join(
          directory,
          ".github",
          key === "policy"
            ? "factory-review-policy.json"
            : key === "requiredChecks"
              ? "required-checks.json"
              : "pull-request-reviewer.json",
        ),
        JSON.stringify(value),
      );
    }
  }
  writeFileSync(
    statePath,
    JSON.stringify({
      head,
      checks: [
        { __typename: "StatusContext", context: "CI", state: "SUCCESS" },
      ],
      ...state,
    }),
  );
  const result = spawnSync(
    process.execPath,
    [
      "--input-type=module",
      "-e",
      `import { main } from ${JSON.stringify(targetURL.href)}; import { connect } from ${JSON.stringify(bundleURL.href)}; import { fixtureConnection } from ${JSON.stringify(new URL("./fixtures/postern-babysit.mjs", import.meta.url).href)}; try { const code = await main(process.argv.slice(1), fixtureConnection(connect)); if (typeof code === "number") process.exitCode = code; } catch (error) { console.error(error.message); process.exitCode = 1; }`,
      "--",
      ...args,
    ],
    {
      cwd: directory,
      encoding: "utf8",
      env: {
        ...process.env,
        PATH: `${directory}:${process.env.PATH}`,
        FAKE_GH_STATE: statePath,
      },
    },
  );
  return { ...result, state: JSON.parse(readFileSync(statePath, "utf8")) };
}

