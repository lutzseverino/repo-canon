test("preserves adoption body bytes with owner-review records in PR comments", (t) => {
  // The caller verifies owner approval under the shared gate. The merge
  // command transports the body; it does not parse or authorize these records.
  const comments = [
    {
      login: "worker[bot]",
      body: "> _This was generated by AI._\n\nOwner review is required by the authoritative implementation contract: https://github.com/example/repository/issues/123#issuecomment-456.",
    },
    {
      login: "worker[bot]",
      body: `> _This was generated by AI._\n\nOwner approval source: https://github.com/example/repository/pull/12#issuecomment-789.\nApproved current head: ${head}.`,
    },
  ];
  for (const newline of ["\n", "\r\n"]) {
    const record = renderedAdoptionRecord.replace(/\n/g, newline);
    for (const breaking of [false, true]) {
      const additions = breaking
        ? "\n## Impact\n\nClaim labels change.\n\n## Migration\n\nRelabel open claims.\n"
        : "";
      const body =
        record +
        `${additions}\n## Related issue\n\nCloses #123\n`.replace(
          /\n/g,
          newline,
        );
      const title = `chore${breaking ? "!" : ""}: adopt repo-canon v0.16.0 with CLI 8.0.0`;
      const result = run(t, { title, body, comments });
      assert.equal(result.status, 0, result.stderr);
      assert.equal(result.state.merge.title, `${title} (#12)`);
      assert.equal(result.state.merge.body, body);
      assert.equal(result.state.merge.body.slice(0, record.length), record);
      assert.match(result.state.merge.body, /Closes #123\r?\n$/);
      assert.deepEqual(result.state.comments, comments);
    }
  }
});

