test("refuses the factory's readiness with an attestation that does not back it", async (t) => {
  const refused = (options, reason) => {
    const state = assertRefused(decideIssueContract(accepted(options)), reason);
    assert.match(
      state.rejectionReason,
      /not backed by a valid factory review attestation/,
    );
    return state;
  };
  await t.test("an attestation by another author", () => {
    const s = accepted();
    s.comments[1] = attestation({ author: "someone" });
    const state = assertRefused(
      decideIssueContract(s),
      /@someone posted is not the configured triage author's/,
    );
    // Only the configured author's attestation is ever observed.
    assert.equal(state.format, resultFormat);
    assert.equal(state.factoryReview, undefined);
  });
  await t.test("an attestation without a run marker", () =>
    refused(
      { attested: attestation({ body: reviewAttestationLine(facts()) }) },
      /no single line marked `factory:run`/,
    ),
  );
  await t.test("an attestation with two run markers", () =>
    refused(
      {
        attested: attestation({
          body: `${runLine("triage-7")}\n${runLine("triage-7")}\n${reviewAttestationLine(facts())}`,
        }),
      },
      /no single line marked/,
    ),
  );
  await t.test("an attestation copied under another run's marker", () =>
    refused(
      { attested: attestation({ run: "triage-8" }) },
      /names run "triage-7", not triage-8/,
    ),
  );
  for (const [
    name,
    changes,
    reason,
  ] of /** @type {[string, any, RegExp][]} */ ([
    [
      "another repository",
      { repository: "other/repository" },
      /another repository/,
    ],
    ["another issue", { issue: "ISSUE_43" }, /another issue/],
    [
      "another revision",
      { revision: `sha256:${"0".repeat(64)}` },
      /another revision/,
    ],
    [
      "another source",
      { source: { type: "issue-body", editedAt: "2026-11-17T09:30:00Z" } },
      /another body source/,
    ],
  ]))
    await t.test(`an attestation naming ${name}`, () =>
      refused(
        {
          attested: attestation({
            line: reviewAttestationLine(facts(directIssue(), changes)),
          }),
        },
        reason,
      ),
    );
  await t.test("an edited attestation", () => {
    const s = accepted();
    s.sourceEdits.COMMENT_20 = {
      id: "EDIT_20",
      editedAt: "2026-11-17T10:00:08Z",
    };
    assertRefused(decideIssueContract(s), /edited after posting/);
  });
  await t.test("an attestation whose edit history was not read", () => {
    const s = accepted();
    delete s.sourceEdits.COMMENT_20;
    assertRefused(decideIssueContract(s), /edit history was not read/);
  });
  await t.test("an attestation from the run that wrote the issue", () => {
    const issue = directIssue({
      user: { login: factory },
      body: `${ticketBody}\n\n${runLine("triage-7")}`,
    });
    const line = reviewAttestationLine(facts(issue));
    refused(
      { issue, attested: attestation({ line }) },
      /triage run triage-7 wrote this issue/,
    );
  });
  await t.test("an issue the factory opened without naming its writer", () => {
    const issue = directIssue({ user: { login: factory } });
    refused({ issue }, /without naming the run that wrote it/);
  });
  await t.test("no attestation at all", () =>
    assertRefused(
      decideIssueContract(snapshot({ attested: null })),
      /posted no review attestation/,
    ),
  );
});

