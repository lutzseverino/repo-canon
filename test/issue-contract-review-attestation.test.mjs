const facts = (issue = directIssue(), changes = {}) => ({
  repository,
  issue: "ISSUE_42",
  run: "triage-7",
  revision: bodyRevision(issue, issue.lastEditedAt ?? null, kindOf(issue.body)),
  source,
  ...changes,
});
/** @param {Record<string, any>} [options] */
const attestation = ({
  id = 20,
  author = factory,
  run = "triage-7",
  line = reviewAttestationLine(facts()),
  body = `> _This was generated by AI._\n\nFactory triage reviewed this revision and found it holding.\n\n${runLine(run)}\n${line}`,
} = {}) => ({
  id,
  node_id: `COMMENT_${id}`,
  body,
  user: { login: author },
  created_at: "2026-11-17T10:00:06Z",
  updated_at: "2026-11-17T10:00:06Z",
});
const unedited = (...comments) =>
  Object.fromEntries(
    comments.map((comment) => [
      comment.node_id,
      { id: `created:${comment.node_id}`, editedAt: null },
    ]),
  );
// The validator's notice of the revision, before any attestation.
const revisionNotice = (issue = directIssue()) => ({
  id: 13,
  body: feedbackState({
    status: "awaiting-review",
    revision: bodyRevision(
      issue,
      issue.lastEditedAt ?? null,
      kindOf(issue.body),
    ),
    kind: kindOf(issue.body),
  }),
  user: bot,
  updated_at: "2026-11-17T10:00:05Z",
});
const readiness = (actor = factory, created_at = "2026-11-17T10:00:10Z") => ({
  id: 4,
  event: "labeled",
  label: { name: "state:ready" },
  actor: { login: actor },
  created_at,
});

/** @param {Record<string, any>} [options] */
function snapshot({
  issue = directIssue(),
  attested = attestation(),
  comments = [revisionNotice(issue), ...(attested ? [attested] : [])],
  actor = factory,
  configured = triageResult,
  sourceEdits = attested ? unedited(attested) : {},
  issueEvents = [readiness(actor)],
  event = neutralEvent({
    action: "labeled",
    label: { name: "state:ready" },
    sender: { login: actor },
  }),
} = {}) {
  return {
    repository,
    event,
    issue,
    comments,
    blockedBy: [],
    parent: null,
    bodyRevision: { id: "ISSUE_42", lastEditedAt: issue.lastEditedAt ?? null },
    issueEvents,
    permissions: { maintainer: role("admin"), [factory]: { role: null } },
    triageResult: configured,
    sourceEdits: {
      ISSUE_42: {
        id: issue.lastEditedAt ? "BODY_EDIT" : "created:ISSUE_42",
        editedAt: issue.lastEditedAt ?? null,
      },
      ...sourceEdits,
    },
    sourceHistory: {
      ISSUE_42: { complete: true, edits: [] },
      ...Object.fromEntries(
        comments.map((comment) => [
          comment.node_id,
          { complete: true, edits: [] },
        ]),
      ),
    },
  };
}

const labelName = (label) => (typeof label === "string" ? label : label.name);
// The notice the validator publishes after evaluating the attestation's
// comment event, before anyone applies readiness, written at `updatedAt`.
function noticeAfter(s, updatedAt = "2026-11-17T10:00:07Z") {
  const attested = s.comments.at(-1);
  const decision = decideIssueContract({
    ...s,
    event: neutralEvent({
      action: "created",
      comment: attested,
      sender: { login: labelName(attested.user.login) },
    }),
    issue: {
      ...s.issue,
      labels: s.issue.labels.filter(
        (label) => labelName(label) !== "state:ready",
      ),
    },
    issueEvents: [],
  });
  return {
    id: 13,
    body: decision.feedback.body,
    user: bot,
    updated_at: updatedAt,
  };
}
// A snapshot whose readiness follows the notice that named its attestation.
/** @param {Record<string, any>} [options] */
function accepted(options = {}) {
  const s = snapshot(options);
  s.comments = [noticeAfter(s), ...s.comments.slice(1)];
  return s;
}

const stateOf = (decision) => publishedState(decision.feedback.body);

function assertApproved(decision, reviewer = factory) {
  assert.equal(decision.exitCode, 0, decision.message);
  assert.deepEqual(decision.removeLabels, []);
  const state = stateOf(decision);
  assert.equal(state.status, "approved");
  assert.equal(state.reviewer, reviewer);
  assert.equal(state.reviewEventId, "4");
  return state;
}

function assertRefused(decision, reason) {
  assert.equal(decision.exitCode, 1, decision.message);
  assert.deepEqual(decision.removeLabels, ["state:ready"]);
  assert.match(decision.message, reason);
  const state = stateOf(decision);
  assert.equal(state.status, "awaiting-review");
  assert.match(state.rejectionReason, reason);
  return state;
}

test("the module produces a review attestation and verifies it", () => {
  const line = reviewAttestationLine(facts());
  assert.ok(line.startsWith(`<!-- ${reviewAttestationMarker} {`));
  assert.deepEqual(attestationPayload(line, reviewAttestationMarker), {
    format: reviewAttestationFormat,
    ...facts(),
  });
  assert.equal(verifyReviewAttestation(`Notes.\n${line}`, facts()), null);
  assert.equal(verifyReviewAttestation(`Notes.\r\n${line}\r\n`, facts()), null);
  for (const [changes, reason] of /** @type {[any, RegExp][]} */ ([
    [{ repository: "other/repository" }, /another repository/],
    [{ issue: "ISSUE_43" }, /another issue/],
    [{ run: "triage-8" }, /names run "triage-7", not triage-8/],
    [{ revision: `sha256:${"0".repeat(64)}` }, /another revision/],
    [
      { source: { type: "issue-body", editedAt: "2026-11-17T10:00:00Z" } },
      /another body source/,
    ],
  ]))
    assert.match(
      verifyReviewAttestation(line, facts(directIssue(), changes)),
      reason,
    );
  assert.match(
    verifyReviewAttestation(`${line}\n${line}`, facts()),
    /no single well-formed/,
  );
  assert.match(
    verifyReviewAttestation("No attestation.", facts()),
    /no single/,
  );
  const payload = attestationPayload(line, reviewAttestationMarker);
  const restated = (value) =>
    `<!-- ${reviewAttestationMarker} ${JSON.stringify(value)} -->`;
  assert.match(
    verifyReviewAttestation(
      restated({ ...payload, format: "repo-canon/review-attestation/v0" }),
      facts(),
    ),
    /format/,
  );
  assert.match(
    verifyReviewAttestation(
      restated({ ...payload, outcome: "success" }),
      facts(),
    ),
    /exactly the fields/,
  );
  for (const invalid of [
    { repository: "repository" },
    { issue: "" },
    { run: " triage-7" },
    { revision: "sha256:abc" },
    { source: { type: "comment", id: "12", editedAt: null } },
    { source: { ...source, editId: "EDIT_1" } },
  ])
    assert.throws(
      () => reviewAttestationLine(facts(directIssue(), invalid)),
      /A review attestation needs/,
    );
});

test("one attestation reader serves the review attestation and the body-mode proof", () => {
  const marker = "repo-canon:triage-attestation";
  const line = `<!-- ${marker} {"format":"repo-canon/triage-attestation/v1"} -->`;
  assert.deepEqual(attestationPayload(`Frame.\n${line}`, marker), {
    format: "repo-canon/triage-attestation/v1",
  });
  for (const body of [
    "",
    `${line}\n${line}`,
    `<!-- ${marker} {"format": -->`,
    `<!-- ${marker} [] -->`,
    `  ${line}`,
  ])
    assert.equal(attestationPayload(body, marker), null, body);
});

test("approves the factory's readiness of a direct ticket with a valid attestation and a later notice", () => {
  const notice = stateOf({ feedback: noticeAfter(snapshot()) });
  assert.equal(notice.format, reviewResultFormat);
  assert.equal(notice.baseFormat, resultFormat);
  assert.equal(notice.status, "awaiting-review");
  assert.deepEqual(notice.factoryReview, {
    run: "triage-7",
    revision: facts().revision,
    attestation: {
      id: "20",
      revision: notice.factoryReview.attestation.revision,
      edit: { id: "created:COMMENT_20", editedAt: null },
    },
    refusal: null,
    publishedAt: null,
  });
  const decision = decideIssueContract(accepted());
  const state = assertApproved(decision);
  assert.equal(state.format, reviewResultFormat);
  assert.equal(state.revision, facts().revision);
  assert.equal(state.factoryReview.refusal, null);
  assert.equal(state.factoryReview.publishedAt, "2026-11-17T10:00:07Z");
  assert.match(
    decision.feedback.body,
    /triage run triage-7, whose review attestation @factory\[bot\] posted/,
  );
  assert.equal(
    issueContractResult(
      [decision.feedback.body].map((body) => ({ body, user: bot })),
    ).state.status,
    "approved",
  );
});

