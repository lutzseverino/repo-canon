test("a recorded approval holds on later runs and ends with its attestation", async (t) => {
  const approvedAfter = () => {
    const s = accepted();
    const decision = decideIssueContract(s);
    s.comments[0] = {
      id: 13,
      body: decision.feedback.body,
      user: bot,
      updated_at: "2026-11-17T10:00:11Z",
    };
    s.event = neutralEvent({
      action: "created",
      comment: { id: 30 },
      sender: { login: "reporter" },
    });
    return s;
  };
  await t.test(
    "a later event keeps the approval and its first notice time",
    () => {
      const state = assertApproved(decideIssueContract(approvedAfter()));
      assert.equal(state.factoryReview.publishedAt, "2026-11-17T10:00:07Z");
    },
  );
  await t.test("deleting the attestation removes readiness", () => {
    const s = approvedAfter();
    const [deleted] = s.comments.splice(1, 1);
    s.event = neutralEvent({
      action: "deleted",
      comment: deleted,
      sender: { login: "someone" },
    });
    const state = assertRefused(
      decideIssueContract(s),
      /review attestation was deleted/,
    );
    assert.equal(state.format, resultFormat);
  });
  await t.test("editing the attestation removes readiness", () => {
    const s = approvedAfter();
    s.sourceEdits.COMMENT_20 = {
      id: "EDIT_20",
      editedAt: "2026-11-17T10:00:12Z",
    };
    const state = assertRefused(decideIssueContract(s), /edited after posting/);
    assert.equal(
      state.factoryReview.refusal,
      "It was edited after posting; post a new attestation instead.",
    );
  });
  await t.test(
    "a body edit removes readiness, as any contract edit does",
    () => {
      const s = approvedAfter();
      s.issue = directIssue({
        body: `${ticketBody}\n\nMore.`,
        lastEditedAt: "2026-11-17T10:00:12Z",
      });
      s.bodyRevision.lastEditedAt = "2026-11-17T10:00:12Z";
      const decision = decideIssueContract(s);
      assert.equal(decision.exitCode, 1);
      assert.deepEqual(decision.removeLabels, ["state:ready"]);
      const state = stateOf(decision);
      assert.equal(state.status, "awaiting-review");
      assert.notEqual(state.revision, facts().revision);
      assert.equal(state.factoryReview.revision, facts().revision);
      assert.match(state.factoryReview.refusal, /another revision/);
    },
  );
});

